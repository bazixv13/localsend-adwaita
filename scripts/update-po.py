#!/usr/bin/env python3
"""Keeps the gettext catalogue in sync with the source.

Extracts every string wrapped in `t(...)`, `fmt(...)` or `np(...)` and writes
`po/localsend-adwaita.pot`. Existing `po/<lang>.po` files keep their
translations; new strings are appended with an empty msgstr. `np()` calls carry
a singular and a plural form, which become a `msgid_plural` entry.

References name the source file only, not the line. A line number changes
whenever anything above a string moves, which made `--check` fail on edits that
touched no text at all.

Usage:
    scripts/update-po.py            # regenerate the POT and compile .mo files
    scripts/update-po.py --check    # fail if the POT on disk is stale (CI)
"""
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
PO_DIR = ROOT / "po"
POT = PO_DIR / "localsend-adwaita.pot"
DOMAIN = "localsend-adwaita"
LOCALE_DIR = PO_DIR / "locale"

STRING = r'"((?:[^"\\]|\\.)*)"'
SINGULAR_PATTERNS = [
    re.compile(r"(?<![\w.])t\(\s*" + STRING + r"\s*\)"),
    re.compile(r"(?<![\w.])fmt\(\s*" + STRING),
]
PLURAL_PATTERN = re.compile(
    r"(?<![\w.])np\(\s*[^,]+?,\s*" + STRING + r"\s*,\s*" + STRING
)

HEADER = """# Translation template for LocalSend for GNOME.
# This file is generated by scripts/update-po.py; do not edit it by hand.
msgid ""
msgstr ""
"Project-Id-Version: localsend-adwaita\\n"
"PO-Revision-Date: 2026-11-20 12:00+0000\\n"
"Last-Translator: LocalSend Adwaita Contributors\\n"
"Language-Team: English\\n"
"Report-Msgid-Bugs-To: https://github.com/bazixv13/localsend-adwaita/issues\\n"
"MIME-Version: 1.0\\n"
"Content-Type: text/plain; charset=UTF-8\\n"
"Content-Transfer-Encoding: 8bit\\n"
"Language: en\\n"
"Plural-Forms: nplurals=2; plural=(n != 1);\\n"
"""


def unescape(text: str) -> str:
    out = []
    index = 0
    while index < len(text):
        char = text[index]
        if char == "\\" and index + 1 < len(text):
            nxt = text[index + 1]
            out.append({"n": "\n", "t": "\t", "r": "\r", '"': '"', "\\": "\\"}.get(nxt, nxt))
            index += 2
            continue
        out.append(char)
        index += 1
    return "".join(out)


def escape(text: str) -> str:
    return (
        text.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\t", "\\t")
    )


def collect():
    """Returns {msgid: {"ref": ..., "plural": str|None}} in source order."""
    seen = {}
    for path in sorted(SRC.glob("*.rs")):
        lines = path.read_text(encoding="utf-8").splitlines()
        for number, line in enumerate(lines, 1):
            # Test-only strings are not user-facing and must not reach the POT.
            if (
                line.strip() == "#[cfg(test)]"
                and number < len(lines)
                and lines[number].lstrip().startswith("mod tests")
            ):
                break
            for pattern in SINGULAR_PATTERNS:
                for match in pattern.finditer(line):
                    msgid = unescape(match.group(1))
                    if not msgid:
                        continue
                    seen.setdefault(
                        msgid, {"ref": str(path.relative_to(ROOT)), "plural": None}
                    )
            for match in PLURAL_PATTERN.finditer(line):
                msgid = unescape(match.group(1))
                plural = unescape(match.group(2))
                if not msgid or not plural:
                    continue
                entry = seen.setdefault(
                    msgid, {"ref": str(path.relative_to(ROOT)), "plural": None}
                )
                entry["plural"] = plural
    return seen


def render(seen) -> str:
    parts = [HEADER]
    for msgid, info in seen.items():
        parts.append(f"#: {info['ref']}\n")
        parts.append(f'msgid "{escape(msgid)}"\n')
        if info["plural"]:
            parts.append(f'msgid_plural "{escape(info["plural"])}"\n')
            parts.append('msgstr[0] ""\nmsgstr[1] ""\n\n')
        else:
            parts.append('msgstr ""\n\n')
    return "".join(parts)


def parse_po(path: pathlib.Path):
    """Returns the header text and an ordered {msgid: translation} mapping.

    Singular translations are strings; plural entries are
    `{"singular": str, "plural": str}`.
    """
    text = path.read_text(encoding="utf-8")
    header_match = re.search(r'msgid ""\nmsgstr ""\n((?:"[^"\n]*"\n)*)', text)
    header = text[: header_match.end()] if header_match else ""
    entries = {}
    for match in re.finditer(
        r'msgid "((?:[^"\\]|\\.)*)"\nmsgid_plural "((?:[^"\\]|\\.)*)"\n'
        r'msgstr\[0\] "((?:[^"\\]|\\.)*)"\nmsgstr\[1\] "((?:[^"\\]|\\.)*)"',
        text,
    ):
        entries[unescape(match.group(1))] = {
            "singular": unescape(match.group(3)),
            "plural": unescape(match.group(4)),
        }
    for match in re.finditer(
        r'msgid "((?:[^"\\]|\\.)*)"\nmsgstr "((?:[^"\\]|\\.)*)"', text
    ):
        entries.setdefault(unescape(match.group(1)), unescape(match.group(2)))
    return header, entries


def merge(seen):
    """Rewrites each .po with the current msgids, keeping translations."""
    for path in sorted(PO_DIR.glob("*.po")):
        header, entries = parse_po(path)
        if not header:
            header = HEADER
        out = [header, "\n"]
        body = []
        for msgid, info in seen.items():
            body.append(f"#: {info['ref']}\n")
            body.append(f'msgid "{escape(msgid)}"\n')
            kept = entries.get(msgid)
            if info["plural"]:
                body.append(f'msgid_plural "{escape(info["plural"])}"\n')
                if isinstance(kept, dict):
                    one, many = kept.get("singular", ""), kept.get("plural", "")
                else:
                    one, many = "", ""
                body.append(f'msgstr[0] "{escape(one)}"\nmsgstr[1] "{escape(many)}"\n\n')
            else:
                translation = kept if isinstance(kept, str) else ""
                body.append(f'msgstr "{escape(translation)}"\n\n')
        out.extend(body)
        path.write_text("".join(out), encoding="utf-8")
        print(f"updated {path.relative_to(ROOT)} ({len(seen)} messages)")


def compile_mo():
    compiler = None
    for candidate in ("msgfmt",):
        try:
            subprocess.run([candidate, "--version"], check=True, capture_output=True)
            compiler = candidate
        except (OSError, subprocess.CalledProcessError):
            continue
    if compiler is None:
        print("msgfmt not found; skipping .mo compilation", file=sys.stderr)
        return
    for path in sorted(PO_DIR.glob("*.po")):
        lang = path.stem
        target = LOCALE_DIR / lang / "LC_MESSAGES" / f"{DOMAIN}.mo"
        target.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run([compiler, "--check", "-o", str(target), str(path)], check=True)
        print(f"compiled {target.relative_to(ROOT)}")


def main() -> int:
    check = "--check" in sys.argv[1:]
    seen = collect()
    rendered = render(seen)
    if check:
        if not POT.exists() or POT.read_text(encoding="utf-8") != rendered:
            print("po/localsend-adwaita.pot is out of date; run scripts/update-po.py", file=sys.stderr)
            return 1
        print(f"translation template is up to date ({len(seen)} messages)")
        return 0
    PO_DIR.mkdir(parents=True, exist_ok=True)
    POT.write_text(rendered, encoding="utf-8")
    print(f"wrote {POT.relative_to(ROOT)} ({len(seen)} messages)")
    merge(seen)
    compile_mo()
    return 0


if __name__ == "__main__":
    sys.exit(main())
